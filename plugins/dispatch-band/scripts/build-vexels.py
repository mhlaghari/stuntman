#!/usr/bin/env python3
"""Shrink the floor's Vexel atlases into terminal frames for the dispatch band.

Usage: build-vexels.py <floor assets dir> <out .ts> [preview.png]
Each frame is a palette (up to 15 colours) and rows of one hex digit per pixel,
`.` for transparent. The mod draws two pixel rows per terminal row with `▀`.
"""
import sys
from PIL import Image

CELL_W, CELL_H = 192, 208
CROP = (36, 4, 156, 204)  # Covers every pose, guitar included.
SIZES = {'band': (10, 16), 'pane': (14, 24)}
SKINS = {'claude': 'claude', 'codex': 'codex', 'opencode': 'deepseek', 'agy': 'gemini', 'laghari': 'laghari'}
POSES = {'idle': (0, 0), 'working': (6, 0), 'thinking': (3, 0), 'needs': (3, 2), 'done': (8, 0), 'failed': (5, 0)}


def shrink(cell, size):
    """Each output pixel takes the most common opaque colour of its block, so edges stay crisp."""
    out = Image.new('RGBA', size, (0, 0, 0, 0))
    bw, bh = cell.width / size[0], cell.height / size[1]
    for y in range(size[1]):
        for x in range(size[0]):
            block = cell.crop((round(x * bw), round(y * bh), round((x + 1) * bw), round((y + 1) * bh)))
            pixels = [p for p in block.getdata() if p[3] >= 128]
            if len(pixels) * 3 >= block.width * block.height:  # Mostly empty blocks stay transparent.
                # The black outline wins only where it fills most of the block.
                lit = [p for p in pixels if p[0] * 3 + p[1] * 6 + p[2] > 400]
                if len(lit) * 10 >= len(pixels) * 3:
                    pixels = lit
                colours = {}
                for p in pixels:
                    key = (p[0] >> 4, p[1] >> 4, p[2] >> 4)
                    colours.setdefault(key, []).append(p)
                group = max(colours.values(), key=len)
                out.putpixel((x, y), tuple(sum(c[i] for c in group) // len(group) for i in range(3)) + (255,))
    return out


def frame(atlas, row, col, size):
    cell = atlas.crop((col * CELL_W, row * CELL_H, (col + 1) * CELL_W, (row + 1) * CELL_H)).crop(CROP)
    small = shrink(cell, size)
    alpha = small.getchannel('A')
    rgb = small.convert('RGB').quantize(colors=15, method=Image.Quantize.MEDIANCUT)
    palette = rgb.getpalette()[:45]
    colours = ['#%02x%02x%02x' % tuple(palette[i:i + 3]) for i in range(0, 45, 3)]
    rows = []
    for y in range(size[1]):
        rows.append(''.join('%x' % rgb.getpixel((x, y)) if alpha.getpixel((x, y)) else '.' for x in range(size[0])))
    return {'palette': colours, 'rows': rows}


def main(src, out, preview=None):
    data = {}
    for key, skin in SKINS.items():
        atlas = Image.open(f'{src}/vexel-{skin}.webp').convert('RGBA')
        data[key] = {pose: {name: frame(atlas, r, c, size) for name, size in SIZES.items()}
                     for pose, (r, c) in POSES.items()}
    lines = ['// Generated by scripts/build-vexels.py from the floor Vexel atlases. Do not edit.',
             "import type { Frame } from '../types'", '',
             'export const VEXELS: Record<string, Record<string, { band: Frame; pane: Frame }>> = {']
    for key, poses in data.items():
        lines.append(f'  {key}: {{')
        for pose, sizes in poses.items():
            parts = ', '.join(f"{n}: {{ palette: {f['palette']!r}, rows: {f['rows']!r} }}" for n, f in sizes.items())
            lines.append(f'    {pose}: {{ {parts} }},')
        lines.append('  },')
    lines.append('}')
    with open(out, 'w', encoding='utf-8', newline='\n') as stream:
        stream.write('\n'.join(lines).replace('"', "'") + '\n')
    if preview:
        sheet = Image.new('RGB', (len(POSES) * 16 * 8, len(SKINS) * 26 * 8), (13, 16, 20))
        for y, poses in enumerate(data.values()):
            for x, sizes in enumerate(poses.values()):
                f = sizes['pane']
                for py, row in enumerate(f['rows']):
                    for px, ch in enumerate(row):
                        if ch != '.':
                            colour = f['palette'][int(ch, 16)]
                            box = Image.new('RGB', (8, 8), colour)
                            sheet.paste(box, ((x * 16 + px) * 8, (y * 26 + py) * 8))
        sheet.save(preview)


if __name__ == '__main__':
    main(*sys.argv[1:4])
